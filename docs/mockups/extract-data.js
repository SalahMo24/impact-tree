// Builds the mockup's data from a real analysis: `node src/cli.js --json` output plus the
// git diff it was computed from. Throwaway tooling for docs/mockups; not shipped.
//
// Usage: node docs/mockups/extract-data.js <result.json> <baseSha> > docs/mockups/data.js
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const [resultPath, baseSha] = process.argv.slice(2);
const repo = path.resolve(__dirname, '../..');
const r = JSON.parse(fs.readFileSync(resultPath, 'utf8'));
const rel = (f) => path.relative(repo, f).split(path.sep).join('/');

const textCache = new Map();
const headText = (file) => {
  if (!textCache.has(file)) textCache.set(file, fs.readFileSync(file, 'utf8'));
  return textCache.get(file);
};
const lineAt = (file, pos) => {
  const t = headText(file);
  const line = t.slice(0, pos).split('\n').length;
  return { line, text: t.split('\n')[line - 1].trim() };
};
const tidySig = (s) => (s || '').replace(/: ⟨inferred⟩/g, '').replace(/ => ⟨inferred⟩/g, '');

function diffHunks(relPath) {
  const out = execFileSync('git', ['diff', '-U3', baseSha, 'HEAD', '--', relPath], { cwd: repo, encoding: 'utf8' });
  const hunks = [];
  let cur = null;
  let oldNo = 0;
  let newNo = 0;
  for (const l of out.split('\n')) {
    const m = /^@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@(.*)$/.exec(l);
    if (m) {
      oldNo = Number(m[1]);
      newNo = Number(m[2]);
      cur = { header: l, lines: [] };
      hunks.push(cur);
      continue;
    }
    if (!cur || l.startsWith('\\')) continue;
    if (l.startsWith('+')) cur.lines.push({ t: '+', n: newNo++, s: l.slice(1) });
    else if (l.startsWith('-')) cur.lines.push({ t: '-', o: oldNo++, s: l.slice(1) });
    else if (l.startsWith(' ')) cur.lines.push({ t: ' ', n: newNo++, o: oldNo++, s: l.slice(1) });
  }
  return hunks;
}

const callerOf = (c) => {
  const at = lineAt(c.file, c.pos);
  const site = (c.callSites || [])[0];
  const siteAt = site ? lineAt(c.file, site.start) : at;
  return {
    label: c.label, relPath: rel(c.file), line: at.line, test: !!c.test,
    callState: c.callState, siteLine: siteAt.line, siteText: siteAt.text,
  };
};

const changes = r.allChanged.map((c) => ({
  label: c.label, relPath: c.relPath, startLine: c.startLine, endLine: c.endLine,
  kinds: c.kinds.map((k) => ({ id: k.id, label: k.label, short: k.short })),
  baseSig: tidySig(c.baseSig), headSig: tidySig(c.headSig),
  callerState: c.callerState, callersComplete: c.callersComplete !== false,
  incompleteReason: c.callersIncompleteReason || null,
  staleCallers: c.staleCallers, callers: c.callers.map(callerOf),
  testState: c.testState, tests: c.tests.map((t) => (typeof t === 'string' ? t : t.label)),
  throwsAdded: c.throwsAdded || [], isRoot: c.isRoot !== false,
}));

const files = [...new Set([
  ...r.allChanged.map((c) => c.relPath), ...r.outside.map((o) => o.relPath),
  ...r.deleted.map((d) => d.relPath), ...r.otherFiles.map((f) => f.path),
])];

const data = {
  base: { ref: r.base.ref, sha: String(r.base.sha).slice(0, 7) },
  title: 'T8 fixes: type-check github.js and tree-provider.js, PR-number review key, outside-functions row',
  number: 15,
  warnings: r.warnings,
  fileStatus: Object.fromEntries(files.map((f) => [f, r.fileStatus[f] || (r.otherFiles.find((o) => o.path === f) || {}).status])),
  changes,
  outside: r.outside.map((o) => ({ relPath: o.relPath, ranges: o.ranges })),
  deleted: r.deleted.map((d) => ({ label: d.label, relPath: d.relPath, startLine: d.startLine })),
  otherFiles: r.otherFiles.map((f) => ({ relPath: f.path, status: f.status })),
  diffs: Object.fromEntries(files.map((f) => [f, diffHunks(f)])),
};

process.stdout.write(`// Generated by extract-data.js from a real analysis of PR #${data.number}.\nwindow.DATA = ${JSON.stringify(data)};\n`);
