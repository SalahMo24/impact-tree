'use strict';
// Small Go files, base and head, whose document symbols gopls gave are recorded in
// ./recorded.json by test/lsp-harness/record-go-symbols.js. test/server-symbols.test.js
// replays them, so it needs no editor and no gopls. Change a text only together with a
// new recording: the test checks each text's hash against the one recorded.

const authBase = `package auth

import (
	"fmt"
)

const limit = 3

var verbose = false

func init() {
	verbose = true
}

func init() {
	fmt.Println("second")
}

// Login logs in.
func Login(user string) error {
	return nil
}

func helper(a, b int) int {
	return a + b
}

func removed() {}

func oldName(x int) int {
	return x
}

type Config struct{ n int }

func (c *Config) Reload() error {
	c.n++
	return nil
}

func (c Config) Size() int {
	return c.n
}

func run() {
	f := func() int { return 1 }
	_ = f()
}
`;

const authHead = `package auth

import (
	"fmt"
	"os"
)

const limit = 4

var verbose = false

func init() {
	verbose = true
}

func init() {
	fmt.Println("second", os.Args)
}

// Login logs in.
func Login(user string, force bool) error {
	return nil
}

func helper(a, b int) int {
	return a + b + limit
}

func newName(x int) int {
	return x
}

type Config struct{ n int }

func (c *Config) Reload() error {
	c.n += 2
	return nil
}

func (c *Config) Size() int {
	return c.n
}

func run() {
	f := func() int { return 2 }
	_ = f()
}

func Added() {}
`;

// A module of its own (tools/go.mod), so the files form a second unit.
const toolBase = `package tool

func Tool() int { return 1 }
`;

const toolHead = `package tool

func Tool() int { return 2 }
`;

// gopls is never asked about these in the test: their services answer is scripted.
const plain = `package auth

func Plain() int { return 1 }
`;

const plainHead = `package auth

func Plain() int { return 2 }
`;

// Generated by name (a .pb.go file).
const generatedBase = `package auth

func Generated() int { return 1 }
`;

const generatedHead = `package auth

func Generated() int { return 2 }
`;

module.exports = {
  'auth.go@base': authBase,
  'auth.go@head': authHead,
  'tool.go@base': toolBase,
  'tool.go@head': toolHead,
  'plain.go@base': plain,
  'plain.go@head': plainHead,
  'api.pb.go@base': generatedBase,
  'api.pb.go@head': generatedHead,
};
