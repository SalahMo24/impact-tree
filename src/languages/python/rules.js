// @ts-check
'use strict';
// Python file rules (docs/MULTI_LANGUAGE_PLAN.md, P1): which files Python analyses, which
// are tests and which are generated, and which project (pyproject.toml, setup.py or
// setup.cfg) a file belongs to. They follow the common pytest and protobuf conventions.

const fs = require('fs');
const path = require('path');
const { slashed } = require('../text');

// Environments and caches hold other projects' code or derived files: not the change under
// review. A directory segment, matched against repository-relative paths, so `rebuild/x.py`
// is source.
const IGNORED_DIR = /(^|\/)(venv|\.venv|site-packages|__pycache__|\.tox)\//;
// Build output, only at the repository root: a package named `build` or `dist` deeper down
// is source (pip's `_internal/operations/build/`), and skipping it would hide its changes.
// Limit: a nested project's own build output is analysed.
const ROOT_OUTPUT_DIR = /^(build|dist)\//;
// pytest's own collection names (`test_*.py`, `*_test.py`) and its shared fixtures file.
const TEST_NAME = /(^|\/)(test_[^/]*|[^/]*_test|conftest)\.py$/;
// Generated by name: the protocol buffers compiler's modules and stubs.
const GENERATED_NAME = /_pb2(_grpc)?\.pyi?$/;
// A generated-code header comment: `# Generated by ...` at the start of a comment line, or
// `@generated` anywhere in a comment line.
const GENERATED_COMMENT = /^\s*#\s*Generated by\b|^\s*#.*@generated\b/;
// How much of a file's head is read for that comment. Generators put it first, so it sits in
// the first lines; a file whose head is longer than this is read only this far, and its
// comment, if later, is missed (it is then analysed).
const GENERATED_HEAD_CHARS = 8192;
// The files that mark a Python project's root.
const PROJECT_FILES = ['pyproject.toml', 'setup.py', 'setup.cfg'];


/**
 * Whether a file's header comment says it is generated. Only the lines before the first
 * line that is neither blank nor a `#` comment are read (a shebang and an encoding line are
 * `#` comments); a marker after code, or inside a docstring, is not looked for.
 * @param {string} text The file's text.
 */
function hasGeneratedComment(text) {
  for (const line of text.slice(0, GENERATED_HEAD_CHARS).split('\n')) {
    const trimmed = line.replace(/\r$/, '');
    if (trimmed.trim() === '') continue;
    if (!/^\s*#/.test(trimmed)) return false;
    if (GENERATED_COMMENT.test(trimmed)) return true;
  }
  return false;
}

/** @type {import('../types').LanguageFileRules} */
const pythonRules = Object.freeze({
  id: 'python',
  displayName: 'Python',
  handles: (relPath) => /\.pyi?$/.test(relPath) && !IGNORED_DIR.test(slashed(relPath)) && !ROOT_OUTPUT_DIR.test(slashed(relPath)),
  isTest: (relPath) => TEST_NAME.test(slashed(relPath)),
  isGenerated: (relPath, text) => GENERATED_NAME.test(slashed(relPath)) || hasGeneratedComment(text),
});

/**
 * The Python project a file belongs to: the nearest directory, from the file's own up to the
 * repository root, with a `pyproject.toml`, `setup.py` or `setup.cfg`. Bounded by the path's
 * depth.
 * @param {string} relPath Repository-relative path of the file.
 * @param {string} repo Absolute repository root.
 * @returns {{ component: string, projectRoot: string }}
 */
function pythonProjectOf(relPath, repo) {
  let dir = path.posix.dirname(slashed(relPath).split(path.sep).join('/'));
  for (;;) {
    const probe = dir === '.' ? repo : path.join(repo, dir);
    if (PROJECT_FILES.some((name) => fs.existsSync(path.join(probe, name)))) {
      return dir === '.' ? { component: '(root)', projectRoot: '' } : { component: dir, projectRoot: dir };
    }
    if (dir === '.' || dir === '/' || dir === '') return { component: '(no pyproject.toml)', projectRoot: '' };
    dir = path.posix.dirname(dir);
  }
}

module.exports = { pythonRules, pythonProjectOf, GENERATED_HEAD_CHARS };
