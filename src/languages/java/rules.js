// @ts-check
'use strict';
// Java file rules (docs/MULTI_LANGUAGE_PLAN.md, J1): which files Java analyses, which are
// tests and which are generated, and which project (pom.xml, build.gradle or
// build.gradle.kts) a file belongs to. They follow the Maven and Gradle layout conventions.

const fs = require('fs');
const path = require('path');
const { slashed } = require('../text');

// Gradle's cache directory: tool state, never source, wherever it is.
const IGNORED_DIR = /(^|\/)\.gradle\//;
// IDE output (`out/`) is ignored, and build output (`target/` for Maven, `build/` for Gradle)
// is generated: handled (listed, so a reviewer sees the change) but not analysed. A package
// can be named `build`, `target` or `out` (Bazel's `com/google/devtools/build/lib`), so these
// count only before the first `src/` segment: build output sits beside a build file, never
// inside a source set. Limit: output a custom build places under `src/` is analysed.
const BUILD_OUTPUT = /^(?:(?!src\/)[^/]+\/)*?(?:target|build)\//;
const IDE_OUTPUT_DIR = /^(?:(?!src\/)[^/]+\/)*?out\//;
// Generator output: annotation processors and code generators write `generated-sources/` and
// `generated-test-sources/`, handled but generated. Not a package name, so at any depth.
const GENERATED_DIR = /(^|\/)(generated-sources|generated-test-sources)\//;
// Maven and Gradle's test source set, at any depth (`module/src/test/java/...`).
const TEST_DIR = /(^|\/)src\/test\//;
// The usual test class names: JUnit, Surefire and Failsafe's default includes.
const TEST_NAME = /(Test|Tests|IT|TestCase)\.java$/;
// A line of the head that says the file is generated: the `@Generated` annotation (on a code
// line) or tag (in a comment), or, in a comment, text that starts with `Generated by` (after
// the comment's own `//`, `/*` or `*`).
const GENERATED_ANNOTATION = /@(\w+\.)*Generated\b/;
const GENERATED_BY = /^(\/\/+|\/\*+|\*+)?\s*Generated by\b/;
// A top-level type declaration: where the header ends. `@interface` counts; `.class` in an
// annotation argument does not (a keyword must start a token and be followed by a name).
const TYPE_DECLARATION = /(^|\s)(class|interface|enum|record|@interface)\s+\w/;
// How much of a file's head is read for that marker. Generators put it in the header or on
// the top-level type, so it sits in the first lines; a file whose head is longer than this
// is read only this far, and a marker past it is missed (the file is then analysed).
const GENERATED_HEAD_CHARS = 8192;
// The files that mark a Java project's root.
const PROJECT_FILES = ['pom.xml', 'build.gradle', 'build.gradle.kts'];


/**
 * Whether a file's head says it is generated: a comment before the top-level type that has
 * `@Generated` or starts with `Generated by`, or a `@Generated` annotation (plain or
 * qualified) on that type. Reading stops at the type's declaration, so `@Generated` or
 * "generated" in later code, strings or prose is not looked for.
 * @param {string} text The file's text.
 */
function hasGeneratedMarker(text) {
  let inBlock = false;
  for (const raw of text.slice(0, GENERATED_HEAD_CHARS).split('\n')) {
    let line = raw.replace(/\r$/, '').trim();
    if (inBlock) {
      if (GENERATED_ANNOTATION.test(line) || GENERATED_BY.test(line)) return true;
      const end = line.indexOf('*/');
      if (end < 0) continue;
      inBlock = false;
      line = line.slice(end + 2).trim();
    }
    if (line === '') continue;
    if (line.startsWith('//')) {
      if (GENERATED_ANNOTATION.test(line) || GENERATED_BY.test(line)) return true;
      continue;
    }
    if (line.startsWith('/*')) {
      if (GENERATED_ANNOTATION.test(line) || GENERATED_BY.test(line)) return true;
      const end = line.indexOf('*/', 2);
      if (end < 0) {
        inBlock = true;
        continue;
      }
      line = line.slice(end + 2).trim();
      if (line === '') continue;
    }
    if (GENERATED_ANNOTATION.test(line)) return true;
    if (TYPE_DECLARATION.test(line)) return false;
  }
  return false;
}

/** @type {import('../types').LanguageFileRules} */
const javaRules = Object.freeze({
  id: 'java',
  displayName: 'Java',
  handles: (relPath) => /\.java$/.test(relPath) && !IGNORED_DIR.test(slashed(relPath)) && !IDE_OUTPUT_DIR.test(slashed(relPath)),
  isTest: (relPath) => TEST_DIR.test(slashed(relPath)) || TEST_NAME.test(slashed(relPath)),
  isGenerated: (relPath, text) => GENERATED_DIR.test(slashed(relPath)) || BUILD_OUTPUT.test(slashed(relPath)) || hasGeneratedMarker(text),
});

/**
 * The Java project a file belongs to: the nearest directory, from the file's own up to the
 * repository root, with a `pom.xml`, `build.gradle` or `build.gradle.kts`. Bounded by the
 * path's depth.
 * @param {string} relPath Repository-relative path of the file.
 * @param {string} repo Absolute repository root.
 * @returns {{ component: string, projectRoot: string }}
 */
function javaProjectOf(relPath, repo) {
  let dir = path.posix.dirname(slashed(relPath).split(path.sep).join('/'));
  for (;;) {
    const probe = dir === '.' ? repo : path.join(repo, dir);
    if (PROJECT_FILES.some((name) => fs.existsSync(path.join(probe, name)))) {
      return dir === '.' ? { component: '(root)', projectRoot: '' } : { component: dir, projectRoot: dir };
    }
    if (dir === '.' || dir === '/' || dir === '') return { component: '(no pom.xml or build.gradle)', projectRoot: '' };
    dir = path.posix.dirname(dir);
  }
}

module.exports = { javaRules, javaProjectOf, GENERATED_HEAD_CHARS };
