// @ts-check
'use strict';
// Java callers without a language server (docs/MULTI_LANGUAGE_PLAN.md, J8): an index of a
// set of Java files, read from their text alone, implementing S1's `SyntacticIndex`
// contract (src/languages/types.js) for `createSyntacticResolver`
// (src/engine/resolver-syntactic.js). Mirrors Go's S4 (../go/syntactic-index.js).
//
// Declarations: J7's outline (`javaOutline`) keyed by `collectJavaSymbols` exactly as the
// changed rows are (J2 keys), so a caller row expands in the tree; types with their
// `extends`/`implements` as written, type parameters, annotations, fields with their types.
//
// Names. A file's package is its `package` declaration. A simple type name resolves, in
// order: the enclosing types and their nested types; single-type imports; the same package
// (implicitly); on-demand imports (`import a.b.*`). A qualified name (`a.b.C`, `Outer.Inner`)
// resolves by its first segment or as a fully qualified name. A name that resolves to none
// of the indexed types is an outside type (`java.lang`, a library): its calls are not calls
// to an indexed declaration. Static imports, single (`import static a.C.m`) and on-demand
// (`import static a.C.*`), bind bare method names.
//
// A call resolves only where the receiver's type is written:
//   - `m(` bare: the innermost enclosing type whose hierarchy has a method `m` (inside an
//     anonymous class, its supertype first), then static imports;
//   - `x.m(`: x a local (`T x`, `var x = new T(…)`, `var x = (T) …`, `x instanceof T x`),
//     a parameter, a field (of the enclosing types and their supertypes), `this`, `X.this`,
//     `a.b` through field types, `a.getB().m(` through the declared return type, a cast
//     `((T) e).m(`, `new T(…).m(`;
//   - `T.m(` static; `super.m(` from the superclass up; `new T(` and `this(`/`super(` the
//     constructors.
//   Methods are looked up through `extends` and `implements` within the index (nearest
//   declaration of the same parameter list wins). Overloads are matched by argument count
//   (varargs: at least the fixed parameters); several of one count are each listed.
// A call whose receiver's type is not known (an untyped lambda parameter, `var x = f()`, a
// type parameter, an array element, a type with an outside supertype that lacks `m`) is an
// unresolved call to its name (`unresolvedCallsTo`). `X::m` is a value use, never a call.
// Calls inside strings, text blocks and comments never count (the lexer skips them).
//
// No answer is complete (CODING_STYLE §1): every `callersOfWithStatus` carries the scope
// note, plus the target's own reasons: interface or overridable dispatch, value uses,
// same-arity overloads, members generated by annotation processing (Lombok and the like),
// and (`partialPackages`, the preview) the files outside the pull request.
//
// Pure: reads only the `{ path, text }` pairs it is given. Budgets (CODING_STYLE §2):
// - files: bounded by its input; the caller chooses them (the preview: the PR's files; the
//   CLI: `pickRepositoryFiles`, ../repository-files.js, 3000 files / 64 MiB).
// - bytes per file: `MAX_FILE_BYTES` (1 MiB, as Go's and Python's). Owner: this module.
//   Enforcement: a longer text is not read. Exhaustion: the file is not indexed, counted in
//   `skipped`, and the scope note says how many files were not indexed. A file the lexer or
//   the outline cannot read is skipped and counted the same way.
// - receiver chains: `MAX_CHAIN_DEPTH` (32) nested receiver lookups for one call; past it
//   the receiver is not typed (the call counts as unresolved).
// - type hierarchy: `MAX_HIERARCHY` (64) types walked per lookup; past it the walk stops
//   and the lookup is open (a method not found counts as unresolved).
// Caches (owner: the index, lifetime: the index's, which never changes; no invalidation
// needed): per-file token arrays and bracket matches, per-use resolutions, per-definition
// locals, per-type hierarchies, the unresolved counts by name.

const path = require('path');
const { lex } = require('./lexer');
const { javaOutline } = require('./outline');

const MAX_FILE_BYTES = 1024 * 1024;
const MAX_CHAIN_DEPTH = 32;
const MAX_HIERARCHY = 64;

// The same reasons as the editor's (./editor-extras.js) where the meaning is the same.
const GENERATED_REASON = 'members generated by annotation processing are not read';
const IMPLICIT_SUPER_REASON = 'a no-argument constructor of a class that is not final: a subclass constructor\'s implicit super() call is not listed';
const PROCESSOR_ANNOTATIONS = new Set([
  'Data', 'Getter', 'Setter', 'Builder', 'SuperBuilder', 'Value', 'RequiredArgsConstructor', 'AllArgsConstructor',
  'NoArgsConstructor', 'ToString', 'EqualsAndHashCode', 'With', 'Wither', 'Delegate', 'Accessors', 'FieldDefaults',
  'UtilityClass', 'Singular', 'AutoValue', 'AutoBuilder', 'AutoOneOf', 'Immutable', 'Mapper',
]);
const KEYWORDS = new Set([
  'abstract', 'assert', 'boolean', 'break', 'byte', 'case', 'catch', 'char', 'class', 'const', 'continue', 'default',
  'do', 'double', 'else', 'enum', 'extends', 'final', 'finally', 'float', 'for', 'goto', 'if', 'implements', 'import',
  'instanceof', 'int', 'interface', 'long', 'native', 'new', 'package', 'private', 'protected', 'public', 'return',
  'short', 'static', 'strictfp', 'super', 'switch', 'synchronized', 'this', 'throw', 'throws', 'transient', 'try',
  'void', 'volatile', 'while', 'true', 'false', 'null', 'yield',
]);
const PRIMITIVES = new Set(['boolean', 'byte', 'char', 'short', 'int', 'long', 'float', 'double', 'void']);
const DECL_BEFORE = new Set(['{', ';', '}', '(', 'final', ':']);
const KIND_PACKAGE = 4;
const TYPE_KINDS = new Set([5, 10, 11]);
const FIELD_KINDS = new Set([8, 14]);
const ANONYMOUS = /^(new\s.*\{\.\.\.\}|\{\.\.\.\})$/;

/**
 * @typedef {import('./lexer').Token} Token
 * @typedef {{ rel: string, file: string, pkg: string, text: string, toks: Token[], match: Int32Array,
 *   single: Map<string, string>, demand: string[], staticSingle: Map<string, string[]>, staticDemand: string[],
 *   types: TypeRec[], defs: DefRec[], byPos: Map<number, DefRec>, anon: Array<{ start: number, end: number, superText: string }>|null,
 *   uses: Use[]|null }} FileRec
 * @typedef {{ fqn: string, simple: string, path: string[], kind: string, file: FileRec, start: number, end: number,
 *   namePos: number, superText: string|null, ifaceTexts: string[], typeParams: Set<string>, methods: Map<string, DefRec[]>,
 *   ctors: DefRec[], fields: Map<string, string>, outer: TypeRec|null, nested: Map<string, TypeRec>,
 *   annotations: string[], final: boolean, hier: { types: TypeRec[], open: boolean }|null }} TypeRec
 * @typedef {{ name: string, key: string, label: string, namePos: number, start: number, end: number,
 *   type: TypeRec|null, file: FileRec, arity: number, varargs: boolean, isCtor: boolean, mods: Set<string>,
 *   annotations: string[], returns: string|null, params: Array<{ name: string, type: string }>, paramKey: string,
 *   typeParams: Set<string>, inInterface: boolean, locals: Map<string, string|null>|null }} DefRec
 * @typedef {{ name: string, pos: number, end: number, at: number, kind: 'call'|'new'|'ref', argc: number }} Use
 * @typedef {DefRec[]|'unresolved'|null} Hit
 * @typedef {{ t: 'type', type: TypeRec, static: boolean } | { t: 'ext' } | { t: 'unk' } | { t: 'pkg', name: string }} Recv
 */

/** @param {Token[]} toks @returns {Int32Array} Each bracket's partner index, -1 when unbalanced. */
function matchBrackets(toks) {
  const m = new Int32Array(toks.length).fill(-1);
  /** @type {number[]} */
  const stack = [];
  const pair = { ')': '(', ']': '[', '}': '{' };
  for (let i = 0; i < toks.length; i++) {
    const t = toks[i];
    if (t.kind !== 'punct') continue;
    if (t.text === '(' || t.text === '[' || t.text === '{') stack.push(i);
    else if (t.text in pair) {
      // Pop to the nearest opener of the same kind (an unbalanced one is left -1).
      for (let s = stack.length - 1; s >= 0; s--) {
        if (toks[stack[s]].text === pair[/** @type {')'|']'|'}'} */ (t.text)]) { m[i] = stack[s]; m[stack[s]] = i; stack.length = s; break; }
      }
    }
  }
  return m;
}

const isIdent = (/** @type {Token|undefined} */ t) => !!t && t.kind === 'ident' && !KEYWORDS.has(t.text);
const isP = (/** @type {Token|undefined} */ t, /** @type {string} */ s) => !!t && t.kind === 'punct' && t.text === s;

/**
 * A type as written from `toks[i]`: `a.b.C<X, Y<Z>>[]`, `int...`. Null when `toks[i]` does
 * not start one or its type arguments do not close.
 * @param {Token[]} toks @param {number} i
 * @returns {{ base: string, end: number, array: boolean, text: string }|null} `end`: the index after it.
 */
function readType(toks, i) {
  const t = toks[i];
  if (!t || t.kind !== 'ident' || (KEYWORDS.has(t.text) && !PRIMITIVES.has(t.text))) return null;
  let base = t.text;
  let j = i + 1;
  for (;;) {
    while (isP(toks[j], '.') && isIdent(toks[j + 1])) { base += `.${toks[j + 1].text}`; j += 2; }
    if (!isP(toks[j], '<')) break;
    let depth = 0;
    for (;;) {
      const a = toks[j];
      if (!a) return null;
      if (isP(a, '<')) depth++;
      else if (isP(a, '>')) { if (--depth === 0) { j++; break; } }
      else if (!(a.kind === 'ident' || isP(a, '.') || isP(a, ',') || isP(a, '?') || isP(a, '&') || isP(a, '[') || isP(a, ']'))) return null;
      j++;
    }
    if (!(isP(toks[j], '.') && isIdent(toks[j + 1]))) break;
  }
  let array = false;
  while (isP(toks[j], '[') && isP(toks[j + 1], ']')) { array = true; j += 2; }
  if (isP(toks[j], '...')) { array = true; j++; }
  return { base, end: j, array, text: base + (array ? '[]' : '') };
}

/** @param {string} text @returns {string[]} The annotation names (last segment) among `text`'s tokens. */
function annotationsIn(text) {
  /** @type {Token[]} */
  const toks = [];
  lex(text, 0, (t) => { toks.push(t); });
  const out = [];
  for (let i = 0; i < toks.length; i++) {
    if (isP(toks[i], '@') && toks[i + 1] && toks[i + 1].kind === 'ident' && toks[i + 1].text !== 'interface') {
      let j = i + 1;
      while (isP(toks[j + 1], '.') && toks[j + 2]) j += 2;
      out.push(toks[j].text);
    }
  }
  return out;
}

/**
 * The index of a set of Java files.
 * @param {Array<{ path: string, text: string }>} sources Repository-relative paths.
 * @param {{ root?: string, scope?: string, notIndexed?: number, partialPackages?: boolean }} [options]
 *   `root`: the repository's directory (answers name absolute files); `scope`: what was
 *   indexed, for the scope note; `notIndexed`: files left out by the caller's own bound;
 *   `partialPackages`: the preview, where the files outside the pull request are not read.
 * @returns {import('../types').SyntacticIndex & { skipped: number, scopeNote: () => string, byFile: Map<string, FileRec>,
 *   allCalls: () => Array<{ file: string, rel: string, pos: number, kind: string, targets: Hit, caller: DefRec|null }> }}
 */
function createJavaSyntacticIndex(sources, { root = '', scope = 'the indexed files', notIndexed = 0, partialPackages = false } = {}) {
  const { collectJavaSymbols } = require('./provider');
  /** @type {Map<string, FileRec>} */
  const byFile = new Map();
  /** @type {Map<string, TypeRec>} */
  const typesByFqn = new Map();
  /** @type {Map<string, Array<{ rec: FileRec, use: Use }>>} */
  const usesByName = new Map();
  let skipped = 0;

  // Pass 1: declarations.
  for (const src of sources) {
    if (typeof src.text !== 'string' || src.text.length > MAX_FILE_BYTES) { skipped++; continue; }
    const rec = parseFile(src.path, src.text);
    if (!rec) { skipped++; continue; }
    byFile.set(rec.file, rec);
  }
  // Pass 2: the uses of every name (resolved lazily, per target).
  for (const rec of byFile.values()) {
    rec.uses = recordUses(rec);
    for (const use of rec.uses) {
      const k = use.kind === 'new' ? `new ${use.name}` : use.name;
      if (!usesByName.has(k)) usesByName.set(k, []);
      /** @type {any} */ (usesByName.get(k)).push({ rec, use });
    }
  }

  /** @param {string} rel @param {string} text @returns {FileRec|null} */
  function parseFile(rel, text) {
    /** @type {Token[]} */
    const toks = [];
    if (lex(text, 0, (t) => { toks.push(t); }) < 0) return null;
    const outline = javaOutline(text);
    if (!outline) return null;
    const pkgSym = outline.find((s) => s.kind === KIND_PACKAGE);
    /** @type {FileRec} */
    const rec = {
      rel, file: root ? path.join(root, rel) : rel, pkg: pkgSym ? pkgSym.name : '', text, toks, match: matchBrackets(toks),
      single: new Map(), demand: [], staticSingle: new Map(), staticDemand: [], types: [], defs: [], byPos: new Map(), anon: null, uses: null,
    };
    readImports(rec);
    /** @type {(syms: any[], outer: TypeRec|null, pathSoFar: string[]) => void} */
    const walk = (syms, outer, pathSoFar) => {
      for (const s of syms) {
        if (!TYPE_KINDS.has(s.kind) || ANONYMOUS.test(s.name)) continue;
        const simple = s.name.replace(/<.*$/s, '').trim();
        const p = [...pathSoFar, simple];
        const t = typeRec(rec, s, simple, p, outer);
        rec.types.push(t);
        typesByFqn.set(rec.pkg ? `${rec.pkg}.${p.join('.')}` : p.join('.'), t);
        if (outer) outer.nested.set(simple, t);
        walk(s.children || [], t, p);
      }
    };
    walk(outline, null, []);
    for (const sym of collectJavaSymbols(outline, text)) {
      const owner = innermostType(rec, sym.namePos);
      // A method of an enum constant's or a field's anonymous body is no member of the type.
      const prefix = owner ? `${owner.path.join('.')}.` : '';
      const inBody = !owner || !sym.key.startsWith(prefix) || sym.key.slice(prefix.length, sym.key.indexOf('(')).includes('.');
      // J3's sig carries `typeParameters` and `compact` beyond the shared shape.
      const sig = /** @type {any} */ (sym.sig);
      const params = (sym.sig ? sym.sig.params : []).map((/** @type {any} */ pr) => ({ name: pr.name, type: String(pr.type) }));
      /** @type {DefRec} */
      const d = {
        name: sym.isConstructor ? (owner ? owner.simple : sym.simpleName) : sym.simpleName,
        key: sym.key, label: sym.label, namePos: sym.namePos, start: sym.start, end: sym.end,
        type: inBody ? null : owner, file: rec, arity: params.length,
        varargs: params.length > 0 && /\.\.\.$/.test(params[params.length - 1].type),
        isCtor: sym.isConstructor, mods: new Set(sym.modifiers || []), annotations: sym.decorators || [],
        returns: sym.sig ? sym.sig.returns : null, params, paramKey: sym.key.slice(sym.key.indexOf('(')).replace(/#\d+$/, ''),
        typeParams: new Set(sig && sig.typeParameters ? typeParamNames(sig.typeParameters) : []),
        inInterface: sym.inInterface, locals: null,
      };
      // A compact record constructor: the record's components.
      if (d.isCtor && sig && sig.compact && owner) { d.arity = d.paramKey === '()' ? 0 : d.paramKey.split(',').length; }
      rec.defs.push(d);
      rec.byPos.set(d.namePos, d);
      if (d.type) {
        if (d.isCtor) d.type.ctors.push(d);
        else {
          if (!d.type.methods.has(d.name)) d.type.methods.set(d.name, []);
          /** @type {DefRec[]} */ (d.type.methods.get(d.name)).push(d);
        }
      }
    }
    return rec;
  }

  /** @param {string} tp `<T, U extends X>` @returns {string[]} */
  function typeParamNames(tp) {
    const names = [];
    let depth = 0;
    let expect = true;
    for (const m of tp.matchAll(/[\p{L}_$][\p{L}\p{N}_$]*|[<>,]/gu)) {
      const w = m[0];
      if (w === '<') { depth++; expect = depth === 1; } else if (w === '>') depth--;
      else if (w === ',') { if (depth === 1) expect = true; } else if (expect && depth === 1) { names.push(w); expect = false; }
    }
    return names;
  }

  /** @param {FileRec} rec */
  function readImports(rec) {
    const { toks } = rec;
    for (let i = 0; i < toks.length; i++) {
      const t = toks[i];
      if (t.kind !== 'ident') continue;
      if (t.text === 'class' || t.text === 'interface' || t.text === 'enum' || t.text === 'record') break;
      if (t.text !== 'import') continue;
      let j = i + 1;
      const isStatic = toks[j] && toks[j].text === 'static';
      if (isStatic) j++;
      const parts = [];
      let star = false;
      while (toks[j] && !isP(toks[j], ';')) {
        if (toks[j].kind === 'ident') parts.push(toks[j].text);
        else if (isP(toks[j], '*')) star = true;
        j++;
      }
      i = j;
      if (!parts.length) continue;
      const name = parts.join('.');
      if (isStatic && star) rec.staticDemand.push(name);
      else if (isStatic) {
        const m = parts[parts.length - 1];
        const owner = parts.slice(0, -1).join('.');
        if (!rec.staticSingle.has(m)) rec.staticSingle.set(m, []);
        /** @type {string[]} */ (rec.staticSingle.get(m)).push(owner);
      } else if (star) rec.demand.push(name);
      else rec.single.set(parts[parts.length - 1], name);
    }
  }

  /**
   * @param {FileRec} rec @param {any} s The outline's type symbol.
   * @param {string} simple @param {string[]} p @param {TypeRec|null} outer @returns {TypeRec}
   */
  function typeRec(rec, s, simple, p, outer) {
    const { text } = rec;
    const head = text.slice(s.range.start, s.selectionRange.start);
    const word = (/\b(class|interface|enum|record)\s*$/.exec(head.replace(/@interface\s*$/, 'interface')) || [])[1] || 'class';
    // The header after the name, up to the body's `{`.
    /** @type {Token[]} */
    const toks = [];
    lex(text, s.selectionRange.end, (t) => (isP(t, '{') ? false : (toks.push(t), undefined)));
    let k = 0;
    /** @type {string[]} */
    let typeParams = [];
    if (isP(toks[0], '<')) {
      let depth = 0;
      let j = 0;
      for (; j < toks.length; j++) { if (isP(toks[j], '<')) depth++; else if (isP(toks[j], '>') && --depth === 0) break; }
      typeParams = typeParamNames(toks.slice(0, j + 1).map((x) => x.text).join(' '));
      k = j + 1;
    }
    if (isP(toks[k], '(')) { let depth = 0; for (; k < toks.length; k++) { if (isP(toks[k], '(')) depth++; else if (isP(toks[k], ')') && --depth === 0) { k++; break; } } }
    /** @type {string|null} */
    let superText = null;
    /** @type {string[]} */
    const ifaceTexts = [];
    let mode = '';
    while (k < toks.length) {
      const w = toks[k].text;
      if (w === 'extends' || w === 'implements' || w === 'permits') { mode = w; k++; continue; }
      const ty = readType(toks, k);
      if (!ty) { k++; continue; }
      if (mode === 'extends' && word !== 'interface') superText = ty.base;
      else if (mode === 'extends' || mode === 'implements') ifaceTexts.push(ty.base);
      k = ty.end;
    }
    /** @type {TypeRec} */
    const t = {
      fqn: rec.pkg ? `${rec.pkg}.${p.join('.')}` : p.join('.'), simple, path: p, kind: s.kind === 10 ? 'enum' : word, file: rec,
      start: s.range.start, end: s.range.end, namePos: s.selectionRange.start, superText, ifaceTexts, typeParams: new Set(typeParams),
      methods: new Map(), ctors: [], fields: new Map(), outer, nested: new Map(), annotations: annotationsIn(head),
      final: /\bfinal\b/.test(head.replace(/@[\w$.]+(\([^)]*\))?/g, ' ')), hier: null,
    };
    for (const f of s.children || []) {
      if (!FIELD_KINDS.has(f.kind)) continue;
      /** @type {Token[]} */
      const ft = [];
      lex(text.slice(0, f.selectionRange.start), f.range.start, (x) => { ft.push(x); });
      let i = 0;
      for (;;) {
        if (isP(ft[i], '@')) { i += 2; while (isP(ft[i], '.')) i += 2; if (isP(ft[i], '(')) { let d = 0; for (; i < ft.length; i++) { if (isP(ft[i], '(')) d++; else if (isP(ft[i], ')') && --d === 0) { i++; break; } } } continue; }
        if (ft[i] && ft[i].kind === 'ident' && /^(public|protected|private|static|final|transient|volatile)$/.test(ft[i].text)) { i++; continue; }
        break;
      }
      const ty = readType(ft, i);
      if (ty) t.fields.set(f.name, ty.text);
      else if (s.kind === 10 && f.kind === 22) t.fields.set(f.name, simple);
    }
    // Enum constants are fields of the enum's own type.
    if (s.kind === 10) for (const f of s.children || []) if (f.kind === 22) t.fields.set(f.name, simple);
    return t;
  }

  /** @param {FileRec} rec @param {number} pos @returns {TypeRec|null} */
  function innermostType(rec, pos) {
    /** @type {TypeRec|null} */
    let best = null;
    for (const t of rec.types) if (t.start <= pos && pos < t.end && (!best || t.start >= best.start)) best = t;
    return best;
  }

  /** @param {FileRec} rec @param {number} pos @returns {DefRec|null} */
  function innermostDef(rec, pos) {
    /** @type {DefRec|null} */
    let best = null;
    for (const d of rec.defs) if (d.start <= pos && pos < d.end && (!best || d.start >= best.start)) best = d;
    return best;
  }

  /**
   * Every call, constructor call and method reference in a file, by token.
   * @param {FileRec} rec @returns {Use[]}
   */
  function recordUses(rec) {
    const { toks, match } = rec;
    /** @type {Use[]} */
    const uses = [];
    /** @type {Array<{ start: number, end: number, superText: string }>} */
    const anon = [];
    // The type name of each `new T(`: a constructor call, not a call named T.
    const newNames = new Set();
    for (let i = 0; i < toks.length; i++) {
      const t = toks[i];
      if (t.kind !== 'ident') {
        if (isP(t, '::') && toks[i + 1] && toks[i + 1].kind === 'ident') {
          const n = toks[i + 1];
          uses.push({ name: n.text === 'new' ? '<new>' : n.text, pos: n.start, end: n.end, at: i + 1, kind: 'ref', argc: -1 });
        }
        continue;
      }
      if (t.text === 'new') {
        const ty = readType(toks, i + 1);
        if (!ty || ty.array || !isP(toks[ty.end], '(')) continue;
        const close = match[ty.end];
        if (close < 0) continue;
        const nameTok = toks[ty.end - 1].text === '>' ? toks[i + 1 + 2 * (ty.base.split('.').length - 1)] : toks[ty.end - 1];
        newNames.add(nameTok.start);
        uses.push({ name: ty.base.slice(ty.base.lastIndexOf('.') + 1), pos: nameTok.start, end: nameTok.end, at: i, kind: 'new', argc: argCount(rec, ty.end) });
        if (isP(toks[close + 1], '{') && match[close + 1] > 0) anon.push({ start: toks[close + 1].start, end: toks[match[close + 1]].end, superText: ty.base });
        continue;
      }
      if (!isP(toks[i + 1], '(')) continue;
      if ((t.text === 'this' || t.text === 'super') && !isP(toks[i - 1], '.')) {
        uses.push({ name: t.text === 'this' ? '<this>' : '<super>', pos: t.start, end: t.end, at: i, kind: 'new', argc: argCount(rec, i + 1) });
        continue;
      }
      if (KEYWORDS.has(t.text) || rec.byPos.has(t.start) || newNames.has(t.start)) continue;
      if (isP(toks[i - 1], '@') || isP(toks[i - 1], '::')) continue;
      uses.push({ name: t.text, pos: t.start, end: t.end, at: i, kind: 'call', argc: argCount(rec, i + 1) });
    }
    rec.anon = anon;
    return uses;
  }

  /** @param {FileRec} rec @param {number} open The `(` index. @returns {number} */
  function argCount(rec, open) {
    const { toks, match } = rec;
    const close = match[open];
    if (close < 0) return -1;
    if (close === open + 1) return 0;
    let n = 1;
    for (let j = open + 1; j < close; j++) {
      const x = toks[j];
      if (x.kind === 'punct' && (x.text === '(' || x.text === '[' || x.text === '{') && match[j] > j) { j = match[j]; continue; }
      if (x.kind === 'ident' && x.text === 'new') { const ty = readType(toks, j + 1); if (ty) { j = ty.end - 1; continue; } }
      // Explicit type arguments and generic types in a cast or a lambda's typed parameter.
      if (isP(x, '<') && toks[j - 1] && (toks[j - 1].kind === 'ident' || isP(toks[j - 1], '.'))) {
        const ty = readType(toks, j - 1);
        if (ty && ty.end > j) { j = ty.end - 1; continue; }
      }
      if (isP(x, ',')) n++;
    }
    return n;
  }

  // ---- types and members -----------------------------------------------------------------

  /**
   * The type a name written in `rec` at `pos` denotes: an indexed type, or null for an outside
   * one (or a type parameter: `'tp'`).
   * @param {string} text @param {FileRec} rec @param {TypeRec|null} enc @param {Set<string>} [tps]
   * @returns {TypeRec|null|'tp'}
   */
  function resolveTypeName(text, rec, enc, tps) {
    const base = text.replace(/<.*$/s, '').replace(/\[\]$/, '').trim();
    if (!base || PRIMITIVES.has(base)) return null;
    const parts = base.split('.');
    const first = parts[0];
    if (parts.length === 1) {
      if (tps && tps.has(first)) return 'tp';
      for (let o = enc; o; o = o.outer) if (o.typeParams.has(first)) return 'tp';
    }
    let head = resolveSimple(first, rec, enc);
    if (head) {
      for (const seg of parts.slice(1)) { head = head && (head.nested.get(seg) || null); }
      if (head) return head;
    }
    return parts.length > 1 ? typesByFqn.get(base) || null : null;
  }

  /** @param {string} name @param {FileRec} rec @param {TypeRec|null} enc @returns {TypeRec|null} */
  function resolveSimple(name, rec, enc) {
    for (let o = enc; o; o = o.outer) {
      if (o.simple === name) return o;
      const n = o.nested.get(name);
      if (n) return n;
      for (const s of hierarchy(o).types.slice(1)) { const m = s.nested.get(name); if (m) return m; }
    }
    const imp = rec.single.get(name);
    if (imp) return typesByFqn.get(imp) || null;
    const same = typesByFqn.get(rec.pkg ? `${rec.pkg}.${name}` : name);
    if (same) return same;
    for (const p of rec.demand) { const t = typesByFqn.get(`${p}.${name}`); if (t) return t; }
    return null;
  }

  /**
   * The type and its supertypes within the index, nearest first. `open`: a supertype is
   * written but not indexed (or the walk hit `MAX_HIERARCHY`), so a member not found may
   * still exist.
   * @param {TypeRec} t @returns {{ types: TypeRec[], open: boolean }}
   */
  function hierarchy(t) {
    if (t.hier) return t.hier;
    t.hier = { types: [t], open: false }; // guards a cycle while it is built
    /** @type {TypeRec[]} */
    const types = [];
    let open = false;
    const queue = [t];
    const seen = new Set();
    while (queue.length) {
      const x = /** @type {TypeRec} */ (queue.shift());
      if (seen.has(x)) continue;
      if (types.length >= MAX_HIERARCHY) { open = true; break; }
      seen.add(x);
      types.push(x);
      for (const s of [x.superText, ...x.ifaceTexts]) {
        if (!s) continue;
        const r = resolveTypeName(s, x.file, x.outer || x, x.typeParams);
        if (r && r !== 'tp') queue.push(r); else if (s !== 'Object') open = true;
      }
    }
    t.hier = { types, open };
    return t.hier;
  }

  /**
   * The methods named `name` a call with `argc` arguments may reach on `t`: across its
   * hierarchy, the nearest declaration of each parameter list. `byName`: whether any method of
   * that name exists at all (Java picks the class by name before the overload).
   * @param {TypeRec} t @param {string} name @param {number} argc @param {boolean} [skipSelf]
   */
  function lookup(t, name, argc, skipSelf = false) {
    const h = hierarchy(t);
    /** @type {Map<string, DefRec>} */
    const found = new Map();
    let byName = false;
    for (const x of skipSelf ? h.types.slice(1) : h.types) {
      for (const d of x.methods.get(name) || []) {
        byName = true;
        if (arityMatches(d, argc) && !found.has(d.paramKey)) found.set(d.paramKey, d);
      }
    }
    return { defs: [...found.values()], byName, open: h.open || generated(t) };
  }
  /** @param {TypeRec} t A Lombok-style type has members this does not see. */
  const generated = (t) => t.annotations.some((a) => PROCESSOR_ANNOTATIONS.has(a));

  /** @param {DefRec} d @param {number} argc */
  const arityMatches = (d, argc) => argc < 0 || (d.varargs ? argc >= d.arity - 1 : argc === d.arity);

  /** @param {DefRec} d @returns {Map<string, string|null>} Parameters and locals by name, null when not typed. */
  function localsOf(d) {
    if (d.locals) return d.locals;
    /** @type {Map<string, string|null>} */
    const out = new Map();
    const set = (/** @type {string} */ n, /** @type {string|null} */ ty) => { out.set(n, out.has(n) && out.get(n) !== ty ? null : ty); };
    for (const p of d.params) set(p.name, p.type.replace(/\.\.\.$/, '[]'));
    const { toks, match } = d.file;
    let i = 0;
    while (i < toks.length && toks[i].start < d.namePos) i++;
    for (; i < toks.length && toks[i].start < d.end; i++) {
      const t = toks[i];
      if (t.kind !== 'ident') {
        // Lambda parameters: `(a, b) ->` and `x ->` are not typed.
        if (isP(t, '->')) {
          if (isIdent(toks[i - 1])) set(toks[i - 1].text, null);
          else if (isP(toks[i - 1], ')') && match[i - 1] >= 0) {
            for (let j = match[i - 1] + 1; j < i - 1; j++) {
              if (isIdent(toks[j]) && (isP(toks[j + 1], ',') || j + 1 === i - 1)) {
                const typed = j > match[i - 1] + 1 && !isP(toks[j - 1], ',') && !isP(toks[j - 1], '(');
                if (!typed) set(toks[j].text, null);
              }
            }
          }
        }
        continue;
      }
      if (t.text === 'instanceof') {
        const ty = readType(toks, i + 1);
        if (ty && isIdent(toks[ty.end])) set(toks[ty.end].text, ty.text);
        continue;
      }
      const prev = toks[i - 1];
      if (!prev || !DECL_BEFORE.has(prev.text)) continue;
      if (KEYWORDS.has(t.text) && !PRIMITIVES.has(t.text) && t.text !== 'final') continue;
      const ty = readType(toks, i);
      if (!ty) continue;
      const nameTok = toks[ty.end];
      const after = toks[ty.end + 1];
      if (!isIdent(nameTok) || !after || !(['=', ';', ',', ':', ')'].includes(after.text))) continue;
      if (ty.base === 'var') {
        // `var x = new T(…)`, `var x = (T) e`; anything else is not typed.
        const r = toks[ty.end + 2];
        let typed = null;
        if (after.text === '=' && r && r.text === 'new') { const nt = readType(toks, ty.end + 3); if (nt && isP(toks[nt.end], '(')) typed = nt.text; }
        else if (after.text === '=' && isP(r, '(')) { const ct = readType(toks, ty.end + 3); if (ct && isP(toks[ct.end], ')')) typed = ct.text; }
        set(nameTok.text, typed);
      } else set(nameTok.text, ty.text);
      i = ty.end;
    }
    d.locals = out;
    return out;
  }

  /** @param {FileRec} rec @param {number} pos @returns {{ start: number, end: number, superText: string }|null} */
  const anonAt = (rec, pos) => {
    let best = null;
    for (const a of rec.anon || []) if (a.start <= pos && pos < a.end && (!best || a.start >= best.start)) best = a;
    return best;
  };

  /**
   * A field's declared type on `t` or its supertypes: the type text and where it is read.
   * @param {TypeRec} t @param {string} name @returns {{ text: string, in: TypeRec }|null}
   */
  function fieldOf(t, name) {
    for (const x of hierarchy(t).types) { const f = x.fields.get(name); if (f) return { text: f, in: x }; }
    return null;
  }

  /** @param {string} text @param {TypeRec} where @param {Set<string>} [tps] @returns {Recv} */
  function recvOfText(text, where, tps) {
    if (/\[\]$/.test(text)) return { t: 'ext' };
    const r = resolveTypeName(text, where.file, where, tps);
    if (r === 'tp') return { t: 'unk' };
    return r ? { t: 'type', type: r, static: false } : { t: 'ext' };
  }

  /**
   * The type of the receiver expression that ends at token `end`.
   * @param {FileRec} rec @param {number} end @param {number} depth @returns {Recv}
   */
  function recvAt(rec, end, depth) {
    if (depth > MAX_CHAIN_DEPTH) return { t: 'unk' };
    const { toks, match } = rec;
    const t = toks[end];
    if (!t) return { t: 'unk' };
    const enc = innermostType(rec, t.start);
    const def = innermostDef(rec, t.start);
    if (t.kind === 'lit') return /^["']/.test(t.text) ? { t: 'ext' } : { t: 'unk' };
    if (t.kind === 'ident') {
      const dotted = isP(toks[end - 1], '.');
      if (t.text === 'this') {
        if (dotted) { const r = resolveTypeName(toks[end - 2].text, rec, enc); return r && r !== 'tp' ? { t: 'type', type: r, static: false } : { t: 'unk' }; }
        if (anonAt(rec, t.start)) return { t: 'unk' };
        return enc ? { t: 'type', type: enc, static: false } : { t: 'unk' };
      }
      if (KEYWORDS.has(t.text)) return { t: 'unk' };
      if (dotted) {
        const base = recvAt(rec, end - 2, depth + 1);
        if (base.t === 'type') {
          const f = fieldOf(base.type, t.text);
          if (f) return recvOfText(f.text, f.in);
          const n = base.type.nested.get(t.text);
          if (n) return { t: 'type', type: n, static: true };
          return hierarchy(base.type).open ? { t: 'unk' } : { t: 'ext' };
        }
        if (base.t === 'pkg') {
          const full = `${base.name}.${t.text}`;
          const ty = typesByFqn.get(full);
          return ty ? { t: 'type', type: ty, static: true } : { t: 'pkg', name: full };
        }
        return base;
      }
      if (def) {
        const locals = localsOf(def);
        if (locals.has(t.text)) {
          const ty = locals.get(t.text);
          return ty ? recvOfText(ty, def.type || /** @type {TypeRec} */ (enc), def.typeParams) : { t: 'unk' };
        }
      }
      for (let o = enc; o; o = o.outer) {
        const f = fieldOf(o, t.text);
        if (f) return recvOfText(f.text, f.in);
      }
      const ty = resolveTypeName(t.text, rec, enc, def ? def.typeParams : undefined);
      if (ty === 'tp') return { t: 'unk' };
      if (ty) return { t: 'type', type: ty, static: true };
      if (/^[a-z]/.test(t.text)) {
        // A lowercase name that is no local, field or type: a package's first segment, or a
        // field inherited from an outside supertype.
        for (let o = enc; o; o = o.outer) if (hierarchy(o).open) return { t: 'unk' };
        return { t: 'pkg', name: t.text };
      }
      return { t: 'ext' };
    }
    if (isP(t, ')')) {
      const open = match[end];
      if (open < 0) return { t: 'unk' };
      const before = toks[open - 1];
      // `new T<…>(…)`
      for (let j = open - 1; j >= 0 && j >= open - 40; j--) {
        const x = toks[j];
        if (x.kind === 'ident' && x.text === 'new') {
          const ty = readType(toks, j + 1);
          if (ty && ty.end === open) {
            const r = resolveTypeName(ty.base, rec, enc, def ? def.typeParams : undefined);
            return r && r !== 'tp' ? { t: 'type', type: r, static: false } : { t: 'ext' };
          }
          break;
        }
        if (!(x.kind === 'ident' || isP(x, '.') || isP(x, '<') || isP(x, '>') || isP(x, ',') || isP(x, '?'))) break;
      }
      if (before && before.kind === 'ident' && !KEYWORDS.has(before.text)) {
        // A call: the declared return type of what it resolves to.
        const use = (rec.uses || []).find((u) => u.at === open - 1 && u.kind === 'call');
        if (!use) return { t: 'unk' };
        const hit = resolveUse(rec, use, depth + 1);
        if (hit === 'unresolved') return { t: 'unk' };
        if (!hit || !hit.length) return { t: 'ext' };
        const rets = new Set(hit.map((d) => d.returns));
        if (rets.size !== 1) return { t: 'unk' };
        const d = hit[0];
        if (!d.returns || !d.type) return { t: 'unk' };
        return recvOfText(d.returns, d.type, d.typeParams);
      }
      if (before && before.kind === 'ident') return { t: 'unk' }; // `if (…)`, `this(…)`
      // `((T) e)` or `(e)`.
      if (isP(toks[open + 1], '(') && match[open + 1] > open + 1) {
        const inner = match[open + 1];
        const ty = readType(toks, open + 2);
        if (ty && ty.end === inner && inner + 1 < end) {
          if (ty.array) return { t: 'ext' };
          const r = resolveTypeName(ty.base, rec, enc, def ? def.typeParams : undefined);
          return r === 'tp' ? { t: 'unk' } : r ? { t: 'type', type: r, static: false } : { t: 'ext' };
        }
      }
      if (end - 1 > open) return recvAt(rec, end - 1, depth + 1);
      return { t: 'unk' };
    }
    return { t: 'unk' };
  }

  // Cache: each use's resolution, keyed by the use object (owner and lifetime: the index's).
  /** @type {Map<Use, Hit>} */
  const resolved = new Map();

  /**
   * The declarations a use reaches: a list (several when overloads of one argument count
   * match), `'unresolved'` when the receiver's type is not known, null for a call to
   * something outside the index.
   * @param {FileRec} rec @param {Use} use @param {number} [depth] @returns {Hit}
   */
  function resolveUse(rec, use, depth = 0) {
    if (resolved.has(use)) return /** @type {Hit} */ (resolved.get(use));
    resolved.set(use, 'unresolved'); // a cycle reads as unresolved
    const hit = resolveUncached(rec, use, depth);
    resolved.set(use, hit);
    return hit;
  }

  /** @param {FileRec} rec @param {Use} use @param {number} depth @returns {Hit} */
  function resolveUncached(rec, use, depth) {
    const { toks } = rec;
    const enc = innermostType(rec, use.pos);
    const def = innermostDef(rec, use.pos);
    const tps = def ? def.typeParams : undefined;
    if (use.kind === 'new') {
      /** @type {TypeRec|null} */
      let t;
      if (use.name === '<this>') t = enc;
      else if (use.name === '<super>') { const s = enc && enc.superText ? resolveTypeName(enc.superText, rec, enc.outer || enc, enc.typeParams) : null; t = s === 'tp' ? null : s; if (enc && enc.superText && !t) return null; }
      else {
        const ty = readType(toks, use.at + 1);
        const r = ty ? resolveTypeName(ty.base, rec, enc, tps) : null;
        t = r === 'tp' ? null : r;
      }
      if (!t) return null;
      const defs = t.ctors.filter((d) => arityMatches(d, use.argc));
      if (!defs.length && generated(t)) return 'unresolved';
      return defs.length ? defs : null;
    }
    if (use.kind === 'ref') {
      if (use.name === '<new>') {
        const r = resolveTypeName(toks[use.at - 2] ? toks[use.at - 2].text : '', rec, enc, tps);
        return r && r !== 'tp' ? r.ctors.slice() : null;
      }
      /** @type {Recv} */
      const recv = use.at >= 2 ? (isP(toks[use.at - 2], ')') || toks[use.at - 2].kind === 'ident' ? recvAt(rec, use.at - 2, depth) : { t: 'unk' }) : { t: 'unk' };
      if (recv.t === 'type') { const l = lookup(recv.type, use.name, -1); return l.defs.length ? l.defs : l.open ? 'unresolved' : null; }
      return recv.t === 'unk' ? 'unresolved' : null;
    }
    const dotted = isP(toks[use.at - 1], '.');
    if (!dotted) {
      // Bare `m(`: the innermost enclosing type whose hierarchy has a method of the name.
      let open = false;
      const anon = anonAt(rec, use.pos);
      if (anon) {
        const s = resolveTypeName(anon.superText, rec, enc, tps);
        if (s && s !== 'tp') {
          const l = lookup(s, use.name, use.argc);
          if (l.byName) return l.defs.length ? l.defs : 'unresolved';
          open = open || l.open;
        } else open = true;
      }
      for (let o = enc; o; o = o.outer) {
        const l = lookup(o, use.name, use.argc);
        if (l.byName) return l.defs.length ? l.defs : null;
        open = open || l.open;
      }
      for (const owner of rec.staticSingle.get(use.name) || []) {
        const t = typesByFqn.get(owner);
        if (t) { const l = lookup(t, use.name, use.argc); if (l.defs.length) return l.defs; } else return null;
      }
      let outsideDemand = false;
      for (const owner of rec.staticDemand) {
        const t = typesByFqn.get(owner);
        if (!t) { outsideDemand = true; continue; }
        const l = lookup(t, use.name, use.argc);
        if (l.defs.length) return l.defs;
      }
      return open || outsideDemand ? 'unresolved' : null;
    }
    const r = toks[use.at - 2];
    if (r && r.kind === 'ident' && r.text === 'super' && !isP(toks[use.at - 3], '.')) {
      if (!enc) return 'unresolved';
      const l = lookup(enc, use.name, use.argc, true);
      return l.defs.length ? l.defs : l.open ? 'unresolved' : null;
    }
    const recv = recvAt(rec, use.at - 2, depth);
    if (recv.t === 'type') {
      const l = lookup(recv.type, use.name, use.argc);
      if (l.defs.length) return l.defs;
      return l.open ? 'unresolved' : null;
    }
    return recv.t === 'unk' ? 'unresolved' : null;
  }

  // ---- the contract ----------------------------------------------------------------------

  const scopeNote = () => `Java callers from syntax only: ${scope}${skipped + notIndexed ? `, ${skipped + notIndexed} Java file(s) not indexed${skipped ? ` (${skipped} unreadable or over ${MAX_FILE_BYTES / 1024 / 1024} MiB)` : ''}` : ''}; calls through an interface or an override, method references, members generated by annotation processing, and receivers whose type is not written are not resolved`;

  /** @param {string} file @param {number|undefined} pos @param {string|null} className @param {string} name @returns {DefRec|null} */
  function targetDef(file, pos, className, name) {
    const rec = byFile.get(file);
    if (!rec) return null;
    const at = pos != null ? rec.byPos.get(pos) : undefined;
    if (at) return at;
    return rec.defs.find((d) => d.name === name && (d.type ? d.type.simple : null) === (className || null)) || null;
  }

  /** @param {DefRec} def @returns {Array<{ rec: FileRec, use: Use }>} */
  const usesOf = (def) => (def.isCtor
    ? [...(usesByName.get(`new ${def.name}`) || []), ...(usesByName.get('new <this>') || []), ...(usesByName.get('new <super>') || []), ...(usesByName.get('<new>') || [])]
    : usesByName.get(def.name) || []);

  /** @param {DefRec} def */
  const overridable = (def) => !def.isCtor && !!def.type && !def.mods.has('static') && !def.mods.has('private')
    && (def.inInterface || (!def.mods.has('final') && !def.type.final && def.type.kind !== 'record'));

  /**
   * @param {{ file: string, className?: string|null, name: string, pos?: number }} target
   * @returns {{ callers: import('../types').SyntacticCaller[], incompleteReason: string }}
   */
  function callersOfWithStatus(target) {
    const def = targetDef(target.file, target.pos, target.className || null, target.name);
    const reasons = [scopeNote()];
    if (!def) return { callers: [], incompleteReason: `${reasons[0]}; the method was not found in the indexed files` };
    /** @type {Map<string, import('../types').SyntacticCaller>} */
    const out = new Map();
    let valueUses = 0;
    let ambiguous = 0;
    let superCalls = 0;
    const supers = def.type && overridable(def)
      ? hierarchy(def.type).types.slice(1).flatMap((t) => (t.methods.get(def.name) || []).filter((d) => d.paramKey === def.paramKey))
      : [];
    for (const { rec, use } of usesOf(def)) {
      if (use.kind === 'ref' && def.isCtor && use.name !== '<new>') continue;
      const hit = resolveUse(rec, use);
      if (!hit || typeof hit === 'string') continue;
      if (!hit.includes(def)) { if (supers.some((s) => hit.includes(s))) superCalls++; continue; }
      if (use.kind === 'ref') { valueUses++; continue; }
      if (hit.length > 1) ambiguous++;
      const owner = innermostDef(rec, use.pos);
      const t = owner ? null : innermostType(rec, use.pos);
      const id = `${rec.file}#${owner ? owner.namePos : t ? t.namePos : 0}`;
      if (!out.has(id)) out.set(id, { file: rec.file, label: owner ? owner.label : t ? t.path.join('.') : path.posix.basename(rec.rel), pos: owner ? owner.namePos : t ? t.namePos : 0, callSites: [] });
      /** @type {any} */ (out.get(id)).callSites.push({ start: use.pos, end: use.end });
    }
    if (def.type && (generated(def.type) || def.annotations.some((a) => PROCESSOR_ANNOTATIONS.has(a)))) reasons.push(GENERATED_REASON);
    if (overridable(def)) {
      reasons.push(`${def.inInterface ? 'an interface method' : 'an overridable method'}: calls are matched by the receiver's written type, so a call written on a supertype or another implementation may run it, and a listed call may run an override${superCalls ? ` (${superCalls} call(s) to the ${supers.map((s) => /** @type {TypeRec} */ (s.type).simple).join(', ')} declaration it overrides)` : ''}`);
    } else if (!def.type) {
      reasons.push('a method of an anonymous or enum-constant body: it is reached through its supertype\'s method, which is not followed');
    }
    if (def.isCtor && def.type && def.arity === 0 && def.type.kind === 'class' && !def.type.final) reasons.push(IMPLICIT_SUPER_REASON);
    if (valueUses) reasons.push(`referenced as a method reference ${valueUses} time(s) (\`X::${def.isCtor ? 'new' : def.name}\`), so its calls through that value cannot be followed`);
    if (ambiguous) reasons.push(`${ambiguous} call(s) match several overloads with the same number of arguments: each such call is listed for every one of them`);
    if (partialPackages) reasons.push('the files outside the pull request were not read');
    return { callers: [...out.values()], incompleteReason: reasons.join('; ') };
  }

  // Cache: count of unresolved calls by name, built on first use (owner, lifetime: the index's).
  /** @type {Map<string, number>} */
  const unresolvedByName = new Map();
  /** @param {{ name: string }} target @returns {number} */
  function unresolvedCallsTo(target) {
    if (unresolvedByName.has(target.name)) return /** @type {number} */ (unresolvedByName.get(target.name));
    let n = 0;
    for (const { rec, use } of usesByName.get(target.name) || []) if (use.kind === 'call' && resolveUse(rec, use) === 'unresolved') n++;
    unresolvedByName.set(target.name, n);
    return n;
  }

  /** @param {string} file @param {number} pos @returns {{ className: string|null, name: string }|null} */
  function symbolAt(file, pos) {
    const d = byFile.get(file)?.byPos.get(pos);
    return d ? { className: d.type ? d.type.simple : null, name: d.name } : null;
  }

  /**
   * Every resolved call in the indexed files (for the verification harness): the call site
   * and the definitions it reaches.
   * @returns {Array<{ file: string, rel: string, pos: number, kind: string, targets: DefRec[]|'unresolved'|null, caller: DefRec|null }>}
   */
  function allCalls() {
    const out = [];
    for (const rec of byFile.values()) {
      for (const use of rec.uses || []) out.push({ file: rec.file, rel: rec.rel, pos: use.pos, kind: use.kind, targets: resolveUse(rec, use), caller: innermostDef(rec, use.pos) });
    }
    return out;
  }

  return { symbolAt, callersOfWithStatus, unresolvedCallsTo, size: byFile.size, skipped, scopeNote, byFile, allCalls };
}

