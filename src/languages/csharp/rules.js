// @ts-check
'use strict';
// C# file rules (Part C, C1): which files C# analyses, which are tests and which are
// generated, and which project (.csproj) a file belongs to. They follow the .NET layout and
// naming conventions.

const fs = require('fs');
const path = require('path');
const { slashed } = require('../text');

// Build output (`bin/`, `obj/`): never source, at any depth.
const BUILD_OUTPUT_DIR = /(^|\/)(bin|obj)\//;
// Generator output by file name: source generators and designers (`*.g.cs`, `*.g.i.cs`,
// `*.designer.cs` in any case, `*.generated.cs`).
const GENERATED_NAME = /\.(g|g\.i|designer|generated)\.cs$/i;
// Entity Framework migrations: `20200514181226_AddActivityLog.cs` and its `.Designer.cs`,
// and the `*ModelSnapshot.cs`. Limit: a hand-edited `Up`/`Down` is listed, not analysed.
// The timestamped name alone is not enough: Jellyfin's `Migrations/Routines/2025..._X.cs` are
// hand-written startup routines with the same name shape, so a plain `.cs` also has to derive
// from EF's `Migration` base class (`.Designer.cs` is generated by name, above).
const EF_MIGRATION = /(^|\/)\d{14}_\w+\.cs$/;
const EF_BASE = /:\s*Migration\b/;
// EF's model snapshot: `*ModelSnapshot.cs` deriving from EF's `ModelSnapshot` (so a
// hand-written `ViewModelSnapshot.cs` is not generated).
const EF_SNAPSHOT = /ModelSnapshot\.cs$/;
const EF_SNAPSHOT_BASE = /:\s*ModelSnapshot\b/;
// The marker generators write in a header comment: `// <auto-generated>` or
// `/// <auto-generated/>`, also inside a block comment.
const AUTO_GENERATED = /<auto-generated/;
// How much of a file's head is read for that marker. A marker past it is missed (the file is
// then analysed).
const GENERATED_HEAD_CHARS = 8192;

/**
 * Whether the file header holds the `<auto-generated` marker: only comments before the first
 * code are read (blank lines, `#` directives, `using …;` and `extern alias …;` are skipped),
 * so the marker in a string literal or in a comment further down (a source generator's own
 * code) does not count.
 * @param {string} head @returns {boolean}
 */
function headerMarked(head) {
  let i = 0;
  const n = head.length;
  while (i < n) {
    const c = head[i];
    if (c === ' ' || c === '\t' || c === '\r' || c === '\n' || c === '\uFEFF') { i++; continue; }
    if (head.startsWith('//', i)) {
      const end = head.indexOf('\n', i);
      const stop = end < 0 ? n : end;
      if (AUTO_GENERATED.test(head.slice(i, stop))) return true;
      i = stop;
      continue;
    }
    if (head.startsWith('/*', i)) {
      const end = head.indexOf('*/', i + 2);
      const stop = end < 0 ? n : end + 2;
      if (AUTO_GENERATED.test(head.slice(i, stop))) return true;
      i = stop;
      continue;
    }
    if (c === '#' || /^(global\s+)?using\s|^extern\s+alias\s/.test(head.slice(i, i + 16))) {
      // A directive runs to the end of its line; a using to its `;`.
      const end = c === '#' ? head.indexOf('\n', i) : head.indexOf(';', i);
      if (end < 0) return false;
      i = end + 1;
      continue;
    }
    return false;
  }
  return false;
}
// A test project's directory: `Foo.Tests/`, `Foo.UnitTests/`, ...
const TEST_PROJECT_DIR = /(^|\/)[^/]*\.(Tests|UnitTests|IntegrationTests|FunctionalTests)\//;
// The usual test file names: `FooTests.cs`. Not `*Test.cs` alone (`SpeedTest.cs`).
const TEST_NAME = /Tests\.cs$/;
// The file that marks a C# project's root.
const PROJECT_FILE = /\.csproj$/;

/** @type {import('../types').LanguageFileRules} */
const csharpRules = Object.freeze({
  id: 'csharp',
  displayName: 'C#',
  handles: (relPath) => /\.cs$/.test(relPath) && !BUILD_OUTPUT_DIR.test(slashed(relPath)),
  isTest: (relPath) => TEST_PROJECT_DIR.test(slashed(relPath)) || TEST_NAME.test(slashed(relPath)),
  isGenerated: (relPath, text) => {
    const p = slashed(relPath);
    if (GENERATED_NAME.test(p)) return true;
    const head = text.slice(0, GENERATED_HEAD_CHARS);
    return (EF_MIGRATION.test(p) && EF_BASE.test(head)) || (EF_SNAPSHOT.test(p) && EF_SNAPSHOT_BASE.test(head)) || headerMarked(head);
  },
});

/**
 * The C# project a file belongs to: the nearest directory, from the file's own up to the
 * repository root, with a `.csproj`. Bounded by the path's depth.
 * @param {string} relPath Repository-relative path of the file.
 * @param {string} repo Absolute repository root.
 * @returns {{ component: string, projectRoot: string }}
 */
function csharpProjectOf(relPath, repo) {
  let dir = path.posix.dirname(slashed(relPath).split(path.sep).join('/'));
  for (;;) {
    const probe = dir === '.' ? repo : path.join(repo, dir);
    let found;
    try {
      found = fs.readdirSync(probe).some((name) => PROJECT_FILE.test(name));
    } catch {
      found = false;
    }
    if (found) return dir === '.' ? { component: '(root)', projectRoot: '' } : { component: dir, projectRoot: dir };
    if (dir === '.' || dir === '/' || dir === '') return { component: '(no .csproj)', projectRoot: '' };
    dir = path.posix.dirname(dir);
  }
}

module.exports = { csharpRules, csharpProjectOf, GENERATED_HEAD_CHARS };
